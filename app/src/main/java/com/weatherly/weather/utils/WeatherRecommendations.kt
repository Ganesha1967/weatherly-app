package com.weatherly.weather.utils

import com.weatherly.weather.domain.model.CurrentWeather

fun getMainAdvice(current: CurrentWeather): String {
    val tempC = current.temp
    val precip = current.precipitationFloat
    val wind = current.windSpeed
    val uv = current.uvIndex

    return when {
        tempC < -15 && wind > 10.0 -> "Экстремальный холод с ветром. Рекомендуется ограничить время на улице"
        tempC < -15 -> "Очень холодно. Минимизируйте пребывание на открытом воздухе"
        tempC in -15..-5 && precip > 0.5f -> "Холодно и возможны осадки. Будьте осторожны на скользких поверхностях"
        tempC in -10..4 && wind > 8.0 -> "Холодно с ощутимым ветром. Ощущается ещё холоднее из-за ветра"
        tempC in -10..4 -> "Холодно. Погода подходит для коротких прогулок при правильной экипировке"
        tempC in 5..14 && precip > 0.3f -> "Прохладно с вероятностью осадков. Зонт не помешает"
        tempC in 5..14 && wind > 6.0 -> "Прохладно и ветрено. Ощущается свежо"
        tempC in 5..14 -> "Прохладно, но комфортно для активных прогулок и спорта на улице"
        tempC in 15..22 && uv > 6f -> "Комфортно, но высокий УФ-индекс. Используйте защиту от солнца"
        tempC in 15..22 && precip < 0.2f -> "Идеальная погода для прогулок, пикников и активного отдыха"
        tempC in 15..22 -> "Комфортная погода. Отличное время для любых активностей на свежем воздухе"
        tempC in 23..30 && current.humidity > 70 -> "Тепло и влажно. Ощущается душновато, пейте больше воды"
        tempC in 23..30 -> "Тепло. Отличная погода для пляжа, велопрогулок и летних активностей"
        tempC > 30 && uv > 8f -> "Очень жарко с экстремальным УФ-индексом. Избегайте солнца с 11:00 до 16:00"
        tempC > 30 && current.humidity > 60 -> "Жарко и душно. Высокий риск перегрева, оставайтесь в тени и пейте воду"
        tempC > 30 -> "Очень жарко. Рекомендуется планировать активности на утро или вечер"
        precip > 0.7f && tempC > 0 -> "Сильный дождь. Рекомендуется переждать непогоду или взять надёжный зонт"
        precip > 0.7f && tempC <= 0 -> "Сильный снегопад. Будьте осторожны на дорогах и тротуарах"
        wind > 12.0 -> "Очень сильный ветер. Не рекомендуется для прогулок с детьми и пожилыми"
        uv > 9f -> "Экстремальный УФ-индекс. Обязательно используйте солнцезащитный крем SPF 50+"
        current.humidity > 90 -> "Очень высокая влажность. Ощущается тяжелее, чем показывает температура"
        else -> "Погода стабильная, без экстремальных условий"
    }
}

fun getClothingTags(
    tempC: Int,
    current: CurrentWeather,
): List<String> =
    buildList {
        when {
            tempC < -10 -> addAll(listOf("Термобельё", "Пуховик", "Перчатки", "Зимние ботинки"))
            tempC in -10..4 -> addAll(listOf("Куртка", "Шарф", "Шапка"))
            tempC in 5..14 -> addAll(listOf("Ветровка", "Кофта", "Джинсы"))
            tempC in 15..22 -> addAll(listOf("Футболка", "Лёгкая кофта"))
            else -> addAll(listOf("Футболка", "Шорты", "Кепка"))
        }

        if (current.precipitationFloat > 0.3f) {
            add("Зонт")
        }
        if (current.uvIndex > 4f) {
            addAll(listOf("Солнцезащитные очки", "SPF"))
        }
        if (tempC < 0 && current.precipitationFloat > 0.1f) {
            add("Непромокаемая обувь")
        }
    }
